-- ============================================================
-- Sync/automation metadata — problem → solution log
--
-- Every ingest pipeline hits recurring failure modes (a row Apps
-- Script sent twice, a device clock skew causing a bad updatedAt,
-- a GSP call that times out). Rather than losing that context in
-- Vercel logs that expire, log it here — it's queryable, joins
-- against the business it happened to, and survives as an audit
-- trail for support/debugging.
-- ============================================================

CREATE TABLE IF NOT EXISTS `YOUR_PROJECT.khatabook.sync_events` (
  id            STRING NOT NULL,
  business_id   STRING,
  source        STRING NOT NULL,   -- e.g. "appscript", "offline_client", "gsp"
  event_type    STRING NOT NULL,   -- e.g. "push_conflict", "gsp_timeout", "duplicate_row"
  table_name    STRING,
  row_id        STRING,
  problem       STRING NOT NULL,   -- what went wrong, in plain language
  resolution    STRING,            -- how it was resolved, or NULL if still open
  status        STRING DEFAULT 'OPEN' NOT NULL,  -- OPEN | RESOLVED | IGNORED
  created_at    TIMESTAMP NOT NULL
)
PARTITION BY DATE(created_at)
CLUSTER BY business_id, status;
