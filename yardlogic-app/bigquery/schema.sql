-- ============================================================
-- Khatabook+ — BigQuery schema
-- Mirrors every table in backend/prisma/schema.prisma exactly.
-- Replace `YOUR_PROJECT.khatabook` with your project + dataset.
--
-- Design notes:
-- - BigQuery has no ENUM type — enum fields are STRING with the
--   allowed values documented in a comment above each column.
--   Apps Script / Vercel should validate against these before insert.
-- - Every business-owned table is PARTITIONed by DATE(created_at)
--   and CLUSTERed by business_id — this is what makes "sales this
--   month for business X" queries cheap instead of full-table scans.
-- - IDs are STRING (UUIDs generated by your app, not BigQuery) so
--   they match the Postgres primary keys 1:1 if you ever need to
--   reconcile the two systems.
-- ============================================================

